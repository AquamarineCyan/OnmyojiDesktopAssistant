"""从 pyproject.toml 生成/校验 requirements*.txt

为什么需要它：
- `pyproject.toml` 是唯一权威来源（CI 用 `uv sync` 读它）；
- 但 README 也让 pip 用户 `pip install -r requirements.txt`，
  所以两份 requirements 必须存在。手工维护三份清单必然漂移——
  修复前 `pydantic>=2.1.0` vs `>=2.13.4`、`pywin32` vs `pywin32==312` 等
  差异会长期静默存在，装出来的环境与 CI 不一致。

用法：
    uv run python tools/sync_requirements.py           # 写入
    uv run python tools/sync_requirements.py --check    # 只校验，漂移则退出码 1
"""
from __future__ import annotations

import argparse
import re
import sys
import tomllib
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[1]
PYPROJECT = REPO_ROOT / "pyproject.toml"
REQUIREMENTS = REPO_ROOT / "requirements.txt"
REQUIREMENTS_GPU = REPO_ROOT / "requirements-gpu.txt"

# GPU 版与 CPU 版的唯一差异：推理引擎。
# CPU 用 onnxruntime，GPU 换成 PaddlePaddle（走 CUDA）。
GPU_ENGINE_SWAP = {
    "onnxruntime": "paddlepaddle-gpu==3.3.1",
}

# 这两份文件的内容必须保持**纯 ASCII**。
# pip 读取 requirements 文件时用的是 `locale.getpreferredencoding()`，
# 不认 UTF-8（除非有 BOM）。中文 Windows 上 locale 是 cp936/GBK，
# 文件里的中文注释会让 pip 直接抛 UnicodeDecodeError 而装不上。
# 需要中文说明请写在 README.md 或 pyproject.toml 里。

GPU_HEADER = """\
# GENERATED by tools/sync_requirements.py from pyproject.toml -- DO NOT EDIT BY HAND
#
# GPU variant. Differs from requirements.txt ONLY in the inference engine:
# paddlepaddle-gpu (CUDA) replaces onnxruntime (CPU).
#
# Engine auto-detection at startup (see src/utils/rapid_model.py):
#   packaged build  -> presence of the `lib/nvidia` directory
#   source run      -> fallback to the `paddlepaddle-gpu` distribution name
# Do NOT use `import paddle` to detect it: the CPU build of `paddlepaddle`
# ships the same `paddle` module, so it would be misdetected as GPU and
# then fail at init with use_cuda=True.
#
# Install in a dedicated virtualenv to avoid clashing with the CPU build:
#     python -m venv .venv-gpu && .venv-gpu\\Scripts\\activate
#     pip install -r requirements-gpu.txt
#
# paddlepaddle-gpu must match your local CUDA/cuDNN.
# See https://www.paddlepaddle.org.cn/install/quick
# Note: paddlepaddle-gpu supports cu129 at most.
--extra-index-url https://www.paddlepaddle.org.cn/packages/stable/cu129/
"""

CPU_HEADER = """\
# GENERATED by tools/sync_requirements.py from pyproject.toml -- DO NOT EDIT BY HAND
# To change dependencies, edit pyproject.toml, then run:
#     uv run python tools/sync_requirements.py
"""

SECTION_RUNTIME = "# --- runtime dependencies ---"
SECTION_DEV = "# --- dev / test tooling ---"


def _load_pyproject() -> dict:
    with open(PYPROJECT, "rb") as f:
        return tomllib.load(f)


def _normalize(name: str) -> str:
    """PEP 503 归一化，用于比较包名（PyYAML / pyyaml 等视为同一个）"""
    return re.sub(r"[-_.]+", "-", name).lower()


def _split_requirement(spec: str) -> tuple[str, str]:
    """把 `httpx>=0.28.1` 拆成 ('httpx', '>=0.28.1')；无版本约束则约束为空串"""
    for sep in ("===", "==", ">=", "<=", "~=", "!=", ">", "<", "@"):
        idx = spec.find(sep)
        if idx != -1:
            return spec[:idx], spec[idx:]
    return spec, ""


def _render(specs: list[str]) -> str:
    return "\n".join(specs) + "\n"


def build_requirements(pyproject: dict, gpu: bool) -> str:
    runtime = list(pyproject["project"]["dependencies"])
    dev = list(pyproject.get("dependency-groups", {}).get("dev", []))

    if gpu:
        swapped = []
        for spec in runtime:
            name, _ = _split_requirement(spec)
            swapped.append(GPU_ENGINE_SWAP.get(_normalize(name), spec))
        runtime = swapped
        header = GPU_HEADER
    else:
        header = CPU_HEADER

    lines = [header]
    lines.append(SECTION_RUNTIME)
    lines.extend(runtime)
    lines.append("")
    lines.append(SECTION_DEV)
    lines.extend(dev)
    return _render(lines)


def check_or_write(pyproject: dict, gpu: bool) -> bool:
    path = REQUIREMENTS_GPU if gpu else REQUIREMENTS
    expected = build_requirements(pyproject, gpu=gpu)
    current = path.read_text(encoding="utf-8") if path.is_file() else ""

    if current == expected:
        print(f"OK   {path.name} 与 pyproject.toml 一致")
        return True

    if "--check" in sys.argv:
        print(f"DRIFT {path.name} 与 pyproject.toml 不一致，请运行：")
        print("      uv run python tools/sync_requirements.py")
        return False

    path.write_text(expected, encoding="utf-8")
    print(f"WROTE {path.relative_to(REPO_ROOT)}")
    return True


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="只校验，不写入；不一致时退出码 1")
    args = parser.parse_args()
    if args.check:
        sys.argv.append("--check")

    pyproject = _load_pyproject()
    ok = check_or_write(pyproject, gpu=False)
    ok = check_or_write(pyproject, gpu=True) and ok
    return 0 if ok else 1


if __name__ == "__main__":
    raise SystemExit(main())
